/** Whole dollars, no cents — this is a podcast promo budget, not a ledger. */
export function money(n: number | null | undefined): string {
  if (n == null) return "—";
  return "$" + Math.round(n).toLocaleString("en-US");
}

export function count(n: number | null | undefined): string {
  if (n == null) return "—";
  if (n >= 1000000) return (n / 1000000).toFixed(1).replace(/\.0$/, "") + "M";
  if (n >= 1000) return (n / 1000).toFixed(1).replace(/\.0$/, "") + "K";
  return String(n);
}

/**
 * Parse a stored date.
 *
 * `new Date("2026-09-10")` is midnight **UTC**, which in New York renders as
 * the 9th — so a campaign starting the 10th displays as starting the day
 * before, everywhere a date-only column is shown. Date-only strings are built
 * from their parts instead, which makes them local midnight and keeps the
 * screen agreeing with the database.
 */
function parseDate(iso: string): Date {
  const dateOnly = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso);
  if (dateOnly) {
    return new Date(+dateOnly[1], +dateOnly[2] - 1, +dateOnly[3]);
  }
  return new Date(iso);
}

/** "12 de octubre" — the date format the owners actually read. */
export function shortDate(iso: string | null | undefined): string {
  if (!iso) return "—";
  const d = parseDate(iso);
  if (Number.isNaN(d.getTime())) return "—";
  return d.toLocaleDateString("es-DO", { day: "numeric", month: "long" });
}

export function daysUntil(iso: string | null | undefined): number | null {
  if (!iso) return null;
  const d = parseDate(iso);
  if (Number.isNaN(d.getTime())) return null;
  const ms = d.setHours(0, 0, 0, 0) - new Date().setHours(0, 0, 0, 0);
  return Math.round(ms / 86400000);
}
