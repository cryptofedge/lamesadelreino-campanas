/**
 * The campaign domain.
 *
 * One idea holds the whole app together: a **campaign** belongs to an
 * **episode**, and fans out into **placements** — one row per platform, each
 * either organic (a post we publish) or paid (an ad we buy).
 *
 * Keeping organic and paid in the same table is the point. Richard does not
 * think "my Instagram post" and "my Instagram ad" as separate projects; he
 * thinks "this week's episode". Splitting them in the data model is what forces
 * people back into five browser tabs.
 */

export type Role = "owner" | "editor";

export type Platform =
  | "youtube"
  | "instagram"
  | "facebook"
  | "tiktok"
  | "x";

export type PlacementKind = "organic" | "paid";

export type CampaignStatus =
  | "draft"      // being built
  | "scheduled"  // approved, waiting for its start date
  | "active"     // running now
  | "done"       // finished
  | "paused";

export type PlacementStatus =
  | "draft"
  | "queued"     // approved here, not yet pushed out
  | "posted"     // organic: published
  | "live"       // paid: spending
  | "finished"
  | "failed";

export type Goal = "views" | "subscribers" | "attendance" | "awareness";

export interface Episode {
  id: string;
  number: number;
  title: string;
  guest: string | null;
  /** When it is recorded. */
  recorded_at: string | null;
  /** When it goes live on YouTube — the date every campaign is timed against. */
  publish_at: string;
  youtube_url: string | null;
  thumbnail_url: string | null;
  notes: string | null;
}

export interface Placement {
  id: string;
  campaign_id: string;
  platform: Platform;
  kind: PlacementKind;
  status: PlacementStatus;
  /** Paid only. Whole dollars — nobody budgets a podcast promo in cents. */
  budget: number | null;
  /** When this specific post/ad goes out. */
  run_at: string | null;
  copy: string;
  /** Image or vertical clip. Generated by the bot or uploaded. */
  creative_url: string | null;
  /** Set once the platform actually has it, so we can reconcile later. */
  external_id: string | null;
  /** Filled in after the fact. Null until the platform reports. */
  reach: number | null;
  clicks: number | null;
  spend: number | null;
}

export interface Campaign {
  id: string;
  episode_id: string;
  name: string;
  goal: Goal;
  status: CampaignStatus;
  budget_total: number;
  starts_at: string;
  ends_at: string;
  created_by: string | null;
  created_at: string;
}

export interface Connection {
  id: string;
  platform: Platform;
  /** An account can be connected for posting, for buying ads, or both. */
  kind: PlacementKind;
  account_name: string;
  connected: boolean;
  /** Why it is not usable, in plain Spanish, when connected is false. */
  blocked_reason: string | null;
  last_checked: string | null;
}

export interface Profile {
  id: string;
  full_name: string | null;
  role: Role;
  must_change_password: boolean;
}

